const express = require('express');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { departamentosInicio } = require('../src/utils/inicioEmpresa');
(async () => {
  const app = express(); app.set('view engine', 'ejs'); app.set('views', path.join(__dirname, '../src/views'));
  app.use(express.static(path.join(__dirname, '../public')));
  const user = { id: 1, rol: 'ADMIN', nombre: 'Prueba', usuario: 'admin', departamentos: ['ADMINISTRACION', 'TALLER'] };
  app.get('/', (_req, res) => res.render('inicio_empresa', { user, departamentos: departamentosInicio(user), next: '' }));
  let news = true;
  app.get('/inicio/noticias', (_req, res) => res.json({ noticias: news ? [{ id: 1, titulo: 'Noticia de prueba', imagen: '/inicio/noticias/1/imagen' }] : [] }));
  app.get('/inicio/noticias/1/imagen', (_req, res) => res.sendFile(path.join(__dirname, '../public/img/logo_tomza.jpg')));
  app.get('/admin/noticias', (_req, res) => res.render('noticias_inicio', { user, noticias: [{ id: 1, titulo: '<Prueba>', orden: 0, activa: 1 }] }));
  app.get('/admin/noticias/1/imagen', (_req, res) => res.sendFile(path.join(__dirname, '../public/img/logo_tomza.jpg')));
  app.use(express.json({ limit: '6mb' })); let requests = 0;
  app.post('/admin/noticias', (req, res) => { assert.ok(req.body.imagen); requests++; res.status(201).json({ id: 2 }); });
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const base = 'http://127.0.0.1:' + server.address().port;
  fs.mkdirSync(path.join(__dirname, '../tmp/noticias'), { recursive: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.clock.install();
    await page.goto(base); await page.waitForSelector('.inicio-carrusel');
    await page.waitForSelector('#sedes-mapa.leaflet-container');
    const before = await page.locator('.inicio-carrusel').boundingBox();
    assert.equal(await page.locator('.inicio-noticia').isVisible(), false);
    await page.clock.fastForward(10100);
    assert.equal(await page.locator('.inicio-noticia').isVisible(), true);
    await page.clock.fastForward(10100);
    assert.equal(await page.locator('.inicio-noticia').isVisible(), false);
    await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
    assert.equal(await page.locator('.inicio-noticia img').getAttribute('alt'), 'Noticia de prueba');
    assert.equal(await page.locator('.sedes-panel').isVisible(), false);
    const after = await page.locator('.inicio-carrusel').boundingBox(); assert.equal(before.height, after.height);
    await page.screenshot({ path: path.join(__dirname, '../tmp/noticias/desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Ver mapa', exact: true }).click();
    assert.equal(await page.locator('.sedes-panel').isVisible(), true);
    assert.equal(await page.getByRole('button', { name: 'Reanudar noticias', exact: true }).count(), 1);
    await page.mouse.move(0, 0); await page.locator('button:focus').evaluateAll(nodes => nodes.forEach(n => n.blur()));
    await page.clock.fastForward(21000);
    assert.equal(await page.locator('.sedes-panel').isVisible(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.ok(await page.locator('.inicio-noticia img').evaluate(img => img.clientHeight > 300));
    await page.screenshot({ path: path.join(__dirname, '../tmp/noticias/movil.png'), fullPage: true });
    news = false; await page.goto(base); assert.equal(await page.locator('.inicio-carrusel').count(), 0); assert.equal(await page.locator('.sedes-panel').isVisible(), true);
    news = true; await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto(base); await page.waitForSelector('.inicio-carrusel');
    assert.equal(await page.getByRole('button', { name: 'Reanudar noticias', exact: true }).count(), 1);
    await page.clock.fastForward(21000); assert.equal(await page.locator('.sedes-panel').isVisible(), true);
    await page.goto(base + '/admin/noticias');
    assert.equal(await page.locator('.noticia-editar input[name=titulo]').inputValue(), '<Prueba>');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: path.join(__dirname, '../tmp/noticias/admin.png'), fullPage: true });
    await page.locator('input[type=file]').setInputFiles(path.join(__dirname, '../public/img/logo_tomza.jpg'));
    await page.getByRole('button', { name: 'Subir imágenes' }).click();
    await page.waitForFunction(() => !document.querySelector('#noticia-subir button').disabled);
    assert.equal(requests, 1);
    console.log('Carrusel: mapa, noticias, pausa, altura estable, movil, vacio y carga verificados.');
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
