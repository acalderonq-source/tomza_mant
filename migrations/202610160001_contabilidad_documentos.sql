CREATE TABLE IF NOT EXISTS cont_documentos_revision (
 documento VARCHAR(100) PRIMARY KEY,
 estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
 empresa VARCHAR(180) NOT NULL DEFAULT '',
 moneda VARCHAR(10) NOT NULL DEFAULT '',
 huella CHAR(64) NOT NULL DEFAULT '',
 motivo TEXT NULL,
 revisado_por INT NULL,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cont_documentos_historial (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 documento VARCHAR(100) NOT NULL,
 estado VARCHAR(20) NOT NULL,
 empresa VARCHAR(180) NOT NULL,
 moneda VARCHAR(10) NOT NULL,
 huella CHAR(64) NOT NULL,
 motivo TEXT NULL,
 actor INT NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_cont_documento_historial (documento,id)
) ENGINE=InnoDB;
