CREATE TABLE IF NOT EXISTS prov_documentos (
 id INT AUTO_INCREMENT PRIMARY KEY,
 tipo VARCHAR(20) NOT NULL,
 usuario_id INT NOT NULL,
 sede VARCHAR(100) NOT NULL,
 datos JSON NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_prov_tipo (tipo, id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prov_inventario (
 sede VARCHAR(100) NOT NULL,
 codigo VARCHAR(80) NOT NULL,
 descripcion VARCHAR(255) NOT NULL,
 iva DECIMAL(5,2) NOT NULL DEFAULT 13,
 cantidad DECIMAL(14,3) NOT NULL DEFAULT 0,
 PRIMARY KEY (sede, codigo)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prov_alertas (
 id INT AUTO_INCREMENT PRIMARY KEY,
 usuario_id INT NULL,
 grupo VARCHAR(30) NULL,
 mensaje VARCHAR(500) NOT NULL,
 documento_id INT NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_prov_alertas_destino (usuario_id, grupo, id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prov_auditoria (
 id INT AUTO_INCREMENT PRIMARY KEY,
 documento_id INT NOT NULL,
 actor VARCHAR(120) NOT NULL,
 accion VARCHAR(100) NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prov_adjuntos (
 id INT AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 mime VARCHAR(50) NOT NULL,
 contenido LONGBLOB NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
