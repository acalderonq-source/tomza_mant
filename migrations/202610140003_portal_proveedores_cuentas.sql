CREATE TABLE IF NOT EXISTS prov_portal_cuentas (
 id INT AUTO_INCREMENT PRIMARY KEY,
 proveedor_id INT NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 cedula VARCHAR(12) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 plazo_dias INT NOT NULL DEFAULT 0,
 activo TINYINT(1) NOT NULL DEFAULT 1,
 version_acceso INT NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prov_portal_receptores (
 cedula VARCHAR(12) PRIMARY KEY,
 nombre VARCHAR(255) NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
